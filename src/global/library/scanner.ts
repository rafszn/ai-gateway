const safeDecode = (value: string): string => {
  try {
    return decodeURIComponent(value);
  } catch {
    return value;
  }
};

export const isScannerPath = (rawPath: string): boolean => {
  const path = safeDecode(rawPath).toLowerCase();

  if (BAD_SUBSTRINGS.some((s) => path.includes(s))) return true;
  if (BAD_PREFIXES.some((p) => path.startsWith(p))) return true;

  const segments = path.split("/").filter(Boolean);
  if (segments.length === 0) return false;

  if (segments.some((s) => BAD_SEGMENTS.has(s))) return true;

  const file = segments[segments.length - 1];
  if (BAD_FILENAMES.has(file)) return true;
  if (BAD_FILENAME_PATTERNS.some((re) => re.test(file))) return true;

  const dot = file.lastIndexOf(".");
  if (dot > 0 && BAD_EXTENSIONS.has(file.slice(dot + 1))) return true;

  return false;
};
